import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { ListOrdered } from 'lucide-react';
import featureImportance from '@/data/feature_importance.json';
import type { FeatureImportanceEntry } from '@/types/charts';
import { axisTick, tooltipStyle } from './chartTheme';

/**
 * Feature importance for the production XGBoost model — train.ipynb cell 27
 * (`booster.get_score(importance_type='gain')` normalized), generated by
 * scripts/generate_chart_data.py. Sorted descending, top feature highlighted: ties the
 * Fare vs Distance scatter back to the model itself.
 */
export function FeatureImportanceChart() {
  const data = [...(featureImportance as FeatureImportanceEntry[])].sort(
    (a, b) => b.importance - a.importance
  );
  const maxImportance = data[0]?.importance ?? 0;

  return (
    <Card className="rounded-lg border">
      <CardHeader className="flex-row items-center gap-2 space-y-0 pb-3">
        <ListOrdered className="h-5 w-5 text-muted-foreground" />
        <div>
          <CardTitle className="text-lg font-semibold">Feature Importance</CardTitle>
          <CardDescription className="text-sm">
            XGBoost gain — why distance drives the fare
          </CardDescription>
        </div>
      </CardHeader>
      <CardContent>
        <ResponsiveContainer width="100%" height={Math.max(data.length * 24, 240)}>
          <BarChart
            data={data}
            layout="vertical"
            margin={{ top: 10, right: 20, left: 10, bottom: 0 }}
          >
            <CartesianGrid strokeDasharray="3 3" stroke="var(--border)" horizontal={false} />
            <XAxis type="number" tick={axisTick} axisLine={false} tickLine={false} />
            <YAxis
              type="category"
              dataKey="feature"
              tick={{ ...axisTick, fontSize: 11 }}
              axisLine={false}
              tickLine={false}
              width={130}
            />
            <Tooltip
              cursor={{ fill: 'var(--accent)' }}
              contentStyle={tooltipStyle}
              formatter={(value) =>
                [`${(Number(value ?? 0) * 100).toFixed(1)}%`, 'Importance'] as [string, string]
              }
            />
            <Bar dataKey="importance" radius={[0, 4, 4, 0]} maxBarSize={14}>
              {data.map((entry) => (
                <Cell
                  key={entry.feature}
                  fill={entry.importance === maxImportance ? 'var(--chart-2)' : 'var(--chart-1)'}
                />
              ))}
            </Bar>
          </BarChart>
        </ResponsiveContainer>
      </CardContent>
    </Card>
  );
}
